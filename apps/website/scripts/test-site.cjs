const assert = require('node:assert/strict');
const path = require('node:path');
const fs = require('node:fs');
const root = path.resolve(__dirname, '..');
const { chromium } = require('playwright');
const { default: AxeBuilder } = require('@axe-core/playwright');
const targetUrl = process.env.TARGET_URL || 'http://127.0.0.1:4181';
const artifacts = process.env.PW_ARTIFACT_DIR || path.join(root, 'test-results');
fs.mkdirSync(artifacts, { recursive: true });
const routes = ['/', '/deploy/', '/pricing/', '/docs/', '/blog/', '/blog/ship-static/', '/blog/frontend-handoff/', '/blog/https-by-default/'];
(async () => {
  const browser = await chromium.launch({ headless: true, executablePath: process.env.CHROME_PATH || undefined });
  const errors = [];
  const results = [];
  try {
    const context = await browser.newContext({ permissions: ['clipboard-read', 'clipboard-write'], viewport: { width: 1440, height: 900 } });
    const page = await context.newPage();
    page.on('pageerror', e => errors.push(e.message));
    page.on('console', m => { if (m.type() === 'error') errors.push(m.text()); });
    page.on('requestfailed', r => errors.push(`${r.url()}: ${r.failure()?.errorText}`));
    const headings = new Set();
    for (const route of routes) {
      const response = await page.goto(targetUrl + route);
      assert.equal(response.status(), 200, route);
      await page.getByRole('heading', { level: 1 }).waitFor();
      const heading = await page.getByRole('heading', { level: 1 }).innerText();
      headings.add(heading);
      assert((await page.title()).includes('Cellapp'));
      assert((await page.locator('meta[name="description"]').getAttribute('content')).length > 30);
      assert.equal(await page.locator('nav [aria-current="page"]').count(), 1);
      await page.reload();
      assert.equal(await page.getByRole('heading', { level: 1 }).innerText(), heading);
      const ax = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze();
      assert.deepEqual(ax.violations.map(v => ({ id: v.id, nodes: v.nodes.map(n => n.target) })), [], `Accessibility ${route}`);
      for (const width of [320, 390, 768, 1440]) {
        await page.setViewportSize({ width, height: 900 });
        assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `Overflow ${route} ${width}`);
      }
      results.push(`Direct load, refresh, metadata, accessibility, 4 widths: ${route}`);
    }
    assert.equal(headings.size, routes.length, 'Each article must have its own content');
    const deployRedirect = await context.request.get(targetUrl + '/deploy', { maxRedirects: 0 });
    assert.equal(deployRedirect.status(), 301);
    assert.equal(deployRedirect.headers().location, '/deploy/');
    results.push('Bare /deploy redirects to the static deployment page');
    await page.goto(targetUrl + '/pricing/');
    await page.getByRole('button', { name: 'Yearly', exact: true }).focus();
    await page.keyboard.press('Enter');
    assert.equal(await page.getByRole('button', { name: 'Yearly', exact: true }).getAttribute('aria-pressed'), 'true');
    assert.match(await page.locator('.plans').innerText(), /\$180 per year · save 21%/);
    assert.match(await page.locator('.plans').innerText(), /\$588 per year · save 17%/);
    await page.getByRole('link', { name: 'Explore Ship' }).click();
    await page.waitForURL('**/docs/?plan=ship&cadence=yearly');
    await page.getByRole('status').filter({ hasText: 'Ship plan preview' }).waitFor();
    assert.equal(await page.getByRole('link', { name: 'Open dashboard' }).getAttribute('href'), '/dashboard');
    await page.getByRole('link', { name: 'Configuration', exact: true }).first().click();
    await page.waitForFunction(() => document.querySelector('aside a[aria-current="location"]')?.getAttribute('href') === '#config');
    results.push('Keyboard pricing cadence, exact savings, selected plan handoff, clipboard, docs active state');
    await page.goto(targetUrl + '/deploy/');
    await page.screenshot({ path: path.join(artifacts, 'cellapp-deploy-desktop.png'), fullPage: true });
    await page.getByRole('button', { name: 'Copy deployment prompt' }).click();
    const copiedPrompt = await page.evaluate(() => navigator.clipboard.readText());
    assert.match(copiedPrompt, /https:\/\/cellapp\.ai\/deploy\/AGENTS\.md/);
    assert.match(copiedPrompt, /log in to Cellapp first if needed/);
    assert.match(copiedPrompt, /supported app database tables/);
    const instructions = await context.request.get(targetUrl + '/deploy/AGENTS.md');
    assert.equal(instructions.status(), 200);
    assert.match(instructions.headers()['content-type'], /text\/markdown|text\/plain/);
    const guide = await instructions.text();
    assert.match(guide, /npm exec --yes --package=@cellapp\/cli@latest -- cellapp --help/);
    assert.match(guide, /cellapp apps --project \./);
    assert(guide.indexOf('## Authorize before long work') < guide.indexOf('## Develop the interface when needed'));
    assert.match(guide, /If a code expires before approval/);
    assert.doesNotMatch(guide, /npm install -g/);
    assert.match(guide, /https:\/\/cellapp\.ai\/deploy\/app-design\.md/);
    assert.match(guide, /\(\.\/AGENTS\.zh-CN\.md\)/);
    const instructionsChinese = await context.request.get(targetUrl + '/deploy/AGENTS.zh-CN.md');
    assert.equal(instructionsChinese.status(), 200);
    assert.match(instructionsChinese.headers()['content-type'], /text\/markdown|text\/plain/);
    const guideChinese = await instructionsChinese.text();
    assert.match(guideChinese, /\(\.\/AGENTS\.md\)/);
    assert.match(guideChinese, /cellapp apps --project \./);
    assert(guideChinese.indexOf('## 在耗时工作前完成授权') < guideChinese.indexOf('## 需要开发界面时'));
    const designGuide = await context.request.get(targetUrl + '/deploy/app-design.md');
    assert.equal(designGuide.status(), 200);
    assert.match(designGuide.headers()['content-type'], /text\/markdown|text\/plain/);
    const designGuideEnglish = await designGuide.text();
    assert.match(designGuideEnglish, /# Design guidance for user apps on Cellapp/);
    assert.match(designGuideEnglish, /\(\.\/app-design\.zh-CN\.md\)/);
    const designGuideChinese = await context.request.get(targetUrl + '/deploy/app-design.zh-CN.md');
    assert.equal(designGuideChinese.status(), 200);
    assert.match(designGuideChinese.headers()['content-type'], /text\/markdown|text\/plain/);
    assert.match(await designGuideChinese.text(), /\(\.\/app-design\.md\)/);
    assert.equal(await page.getByRole('navigation', { name: 'Primary navigation' }).getByRole('link', { name: 'Dashboard' }).getAttribute('href'), '/dashboard');
    results.push('Deployment prompt copy and public Agent Markdown guides');
    await page.setViewportSize({ width: 390, height: 844 });
    await page.goto(targetUrl + '/deploy/');
    await page.screenshot({ path: path.join(artifacts, 'cellapp-deploy-mobile.png'), fullPage: true });
    await page.goto(targetUrl + '/');
    await page.keyboard.press('Tab');
    assert.equal(await page.evaluate(() => document.activeElement.className), 'skip');
    assert(await page.evaluate(() => getComputedStyle(document.activeElement).outlineStyle !== 'none'));
    await page.getByRole('button', { name: 'Menu', exact: true }).click();
    await page.getByRole('navigation', { name: 'Primary navigation' }).getByRole('link', { name: 'Pricing', exact: true }).click();
    await page.waitForURL('**/pricing/');
    await page.screenshot({ path: path.join(artifacts, 'cellapp-pricing-mobile.png'), fullPage: true });
    await page.emulateMedia({ reducedMotion: 'reduce' });
    assert.equal(await page.evaluate(() => getComputedStyle(document.documentElement).scrollBehavior), 'auto');
    results.push('Mobile menu, visible keyboard focus, reduced motion');
    await page.setViewportSize({ width: 1440, height: 900 });
    await page.goto(targetUrl + '/');
    await page.screenshot({ path: path.join(artifacts, 'cellapp-home.png'), fullPage: true });
    await page.goto(targetUrl + '/pricing/');
    await page.screenshot({ path: path.join(artifacts, 'cellapp-pricing.png'), fullPage: true });
    const nojs = await browser.newContext({ javaScriptEnabled: false, viewport: { width: 390, height: 844 } });
    const staticPage = await nojs.newPage();
    for (const route of routes) {
      await staticPage.goto(targetUrl + route);
      assert(await staticPage.getByRole('navigation', { name: 'Primary navigation' }).getByRole('link', { name: 'Pricing', exact: true }).isVisible());
      assert((await staticPage.getByRole('heading', { level: 1 }).innerText()).length > 10);
    }
    results.push(`All ${routes.length} pages readable without JavaScript`);
    await nojs.close();
    await page.goto('file://' + path.join(root, 'dist/bundle.html'));
    await page.getByRole('heading', { level: 1, name: /Ship a frontend/ }).waitFor();
    assert.equal(await page.getByRole('navigation', { name: 'Primary navigation' }).getByRole('link', { name: 'Dashboard' }).getAttribute('href'), 'https://cellapp.ai/dashboard');
    await page.getByRole('navigation', { name: 'Primary navigation' }).getByRole('link', { name: 'Pricing', exact: true }).click();
    await page.getByRole('button', { name: 'Yearly', exact: true }).click();
    await page.getByRole('link', { name: 'Explore Ship' }).click();
    await page.getByRole('heading', { level: 1, name: 'From folder to live app.' }).waitFor();
    await page.getByRole('status').filter({ hasText: 'Ship plan preview' }).waitFor();
    results.push('Portable file:// bundle navigation and plan selection');
    assert.deepEqual(errors, [], 'Browser runtime or resource errors');
    fs.writeFileSync(path.join(artifacts, 'cellapp-validation.json'), JSON.stringify({ results, runtimeErrors: errors }, null, 2));
    console.log(JSON.stringify({ results, runtimeErrors: errors }, null, 2));
  } finally { await browser.close(); }
})().catch(error => { console.error(error.stack); process.exitCode = 1; });
