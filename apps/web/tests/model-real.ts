import assert from 'node:assert/strict';
import { chromium } from 'playwright-core';

const origin = process.env.TEST_MODEL_BROWSER_ORIGIN;
const session = process.env.TEST_MODEL_BROWSER_SESSION;
const app = process.env.TEST_MODEL_BROWSER_APP;
const appUrl = process.env.TEST_MODEL_BROWSER_APP_URL;
if (!origin || !session || !app || !appUrl) throw new Error('Missing isolated model browser configuration');
const executablePath = process.env.CHROME_PATH ?? '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome';
const browser = await chromium.launch({executablePath,headless:true});
try {
  const context = await browser.newContext({ignoreHTTPSErrors:true,viewport:{width:320,height:800}});
  await context.addCookies([{name:'__Host-owner',value:session,url:origin,secure:true,httpOnly:true,sameSite:'Lax'}]);
  const page = await context.newPage();
  await page.goto(origin+'/dashboard/model-connections');
  await page.getByRole('heading',{name:'Model connections',exact:true}).waitFor();
  await page.getByLabel('Name',{exact:true}).fill('Personal');
  await page.getByLabel('HTTPS API base URL').fill('https://127.0.0.1/v1');
  await page.getByLabel('Model ID (optional fallback)').fill('model-one');
  await page.getByLabel('Provider API key').fill('test-secret');
  await page.getByRole('button',{name:'Save connection'}).click();
  await page.getByRole('alert').filter({hasText:'public HTTPS API base URL'}).waitFor();
  await page.getByLabel('HTTPS API base URL').fill('https://models.example.com/v1');
  await page.getByRole('button',{name:'Save connection'}).click();
  await page.getByRole('status').filter({hasText:'Connection saved'}).waitFor();
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth),true);
  assert(!(await page.locator('body').textContent())?.includes('test-secret'));
  await page.getByRole('button',{name:'Test capabilities'}).click();
  try { await page.getByText('Text: Available').waitFor({timeout:5000}); }
  catch (error) { throw new Error(`Model test UI: ${await page.locator('main').textContent()}`,{cause:error}); }
  await page.getByText('Unavailable (invalid_stream)').waitFor();
  await page.goto(origin+`/dashboard/model-consent?app=${app}`);
  await page.getByText('Notes',{exact:true}).waitFor();
  await page.getByRole('radio',{name:/Personal/}).check();
  await page.getByRole('button',{name:'Authorize this application'}).click();
  await page.goto(appUrl);
  await page.getByRole('heading',{name:'Model Agent'}).waitFor();
  await page.getByRole('button',{name:'Run Agent'}).click();
  const modelDialog = page.getByRole('dialog',{name:'Choose a model for this application'});
  await modelDialog.waitFor();
  await modelDialog.getByRole('button',{name:'Use this model'}).click();
  await page.getByText('pong',{exact:true}).waitFor();
  assert((await page.evaluate(() => localStorage.getItem('cellapp:model:v1')))?.startsWith('cellapp:'));
  await page.goto(origin+'/dashboard/model-connections');
  await page.getByText('Authorized provider:').waitFor();
  await page.getByLabel('Name',{exact:true}).fill('Second provider');
  await page.getByLabel('HTTPS API base URL').fill('https://second.example.com/v1');
  await page.getByLabel('Model ID (optional fallback)').fill('model-two');
  await page.getByLabel('Provider API key').fill('other-test-secret');
  await page.getByRole('button',{name:'Save connection'}).click();
  await page.getByRole('status').filter({hasText:'Connection saved'}).waitFor();
  await page.goto(origin+`/dashboard/model-consent?app=${app}`);
  await page.getByRole('radio',{name:/Second provider/}).check();
  await page.getByRole('button',{name:'Authorize this application'}).click();
  await page.goto(origin+'/dashboard/model-connections');
  await page.getByRole('button',{name:'Revoke',exact:true}).nth(1).waitFor();
  assert.equal(await page.getByRole('button',{name:'Revoke',exact:true}).count(),2);
  await page.getByRole('button',{name:'Revoke',exact:true}).first().click();
  await page.getByRole('button',{name:'Confirm',exact:true}).click();
  await page.waitForFunction(() => Array.from(document.querySelectorAll('button')).filter(button => button.textContent?.trim() === 'Revoke').length === 1);
  await page.getByRole('button',{name:'Revoke',exact:true}).click();
  await page.getByRole('button',{name:'Confirm',exact:true}).click();
  await page.getByText('No applications are authorized to use your models.').waitFor();
  const unauthenticated = await browser.newContext({ignoreHTTPSErrors:true});
  const outsider = await unauthenticated.newPage();
  await outsider.goto(origin+'/dashboard/model-connections');
  await outsider.getByRole('heading',{name:'Sign in to Cellapp'}).waitFor();
  assert.equal((await outsider.request.get(origin+'/api/console/model-connections')).status(),401);
  await unauthenticated.close();
  await page.getByRole('button',{name:'Delete',exact:true}).first().click();
  await page.getByRole('button',{name:'Confirm',exact:true}).click();
  await page.waitForFunction(() => Array.from(document.querySelectorAll('button')).filter(button => button.textContent?.trim() === 'Delete').length === 1);
  await page.getByRole('button',{name:'Delete',exact:true}).click();
  await page.getByRole('button',{name:'Confirm',exact:true}).click();
  await page.getByRole('heading',{name:'No model connections'}).waitFor();
  await page.goto(origin+'/dashboard/local-setup');
  await page.getByRole('heading',{name:'Local setup',exact:true}).waitFor();
  await page.getByText('cellapp doctor',{exact:true}).waitFor();
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth),true);
} finally { await browser.close(); }
