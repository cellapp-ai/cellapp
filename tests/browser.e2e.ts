import { chromium, type APIResponse } from 'playwright-core';
import assert from 'node:assert/strict';
import { mkdtemp, mkdir, writeFile, rm, readFile, copyFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { Client } from '../skills/packages/cli/src/client.js';
import { deploy } from '../skills/packages/cli/src/deploy.js';

const origin = process.env.TEST_CONTROL_ORIGIN!;
const root = await mkdtemp(join(tmpdir(), 'cellapp-browser-'));
const browser = await chromium.launch({executablePath: process.env.CHROME_PATH ?? '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true, args: ['--host-resolver-rules=MAP *.localhost 127.0.0.1', `--ignore-certificate-errors-spki-list=${process.env.TEST_BROWSER_SPKI}`]});
try {
  const ownerContext = await browser.newContext({ignoreHTTPSErrors: false});
  const ownerPage = await ownerContext.newPage();
  const client = new Client(origin, join(root, 'credentials'));
  let verification!: (uri: string) => void;
  const ready = new Promise<string>(resolve => { verification = resolve; });
  const loggingIn = client.login(message => { verification(message.match(/https:\/\/\S+/)![0]); });
  await ownerPage.goto(await ready);
  await ownerPage.getByRole('link', {name: 'Continue to sign in'}).click();
  const decisionResponse = ownerPage.waitForResponse(r => r.request().method() === 'POST' && new URL(r.url()).pathname === '/api/console/device/decision');
  await ownerPage.getByRole('button', {name: 'Approve access'}).click();
  assert.equal((await decisionResponse).status(), 200);
  await loggingIn;
  const cli = async (...args: string[]) => {
    const {stdout} = await promisify(execFile)(process.execPath, ['--import', 'tsx', 'skills/packages/cli/src/main.ts', ...args, '--origin', origin, '--config-dir', join(root, 'credentials')]);
    return JSON.parse(stdout);
  };
  const project = join(root, 'project');
  await mkdir(join(project, 'dist'), {recursive: true});
  const demo = 'skills/skills/cellapp-deploy/examples/notes';
  await copyFile(join(demo, 'index.html'), join(project, 'dist', 'index.html'));
  await copyFile(join(demo, 'cellapp.data.json'), join(project, 'cellapp.data.json'));
  await promisify(execFile)('node_modules/.bin/esbuild', [join(demo, 'app.ts'), '--bundle', '--format=esm', '--platform=browser', '--target=es2022', `--outfile=${join(project, 'dist', 'app.js')}`]);
  const first = await deploy(client, project, {output: 'dist', spa: true}, () => {});
  assert.ok('accessKey' in first && first.accessKey && /^[a-f0-9]{64}$/.test(first.accessKey));
  const accessKey = first.accessKey;
  assert.match(first.aliasUrl, /^https:\/\/control\.localhost:\d+\/a\/[a-z][a-z0-9-]+\/[a-z][a-z0-9-]+$/);
  const alias = await ownerContext.request.get(first.aliasUrl, {maxRedirects: 0});
  assert.equal(alias.status(), 307);
  assert.equal(alias.headers()['location'], first.url);
  await ownerPage.goto(first.aliasUrl);
  await ownerPage.getByRole('heading', {name: 'Notes app'}).waitFor();
  assert.equal(new URL(ownerPage.url()).origin, first.url);
  const metadata = JSON.parse(await readFile(join(project, 'cellapp.json'), 'utf8'));
  assert.ok(!JSON.stringify(metadata).includes(accessKey));
  const bundle = await readFile(join(project, 'dist', 'app.js'), 'utf8');
  for (const secret of [accessKey, 'postgres://', 'local-development-postgrest-jwt-secret-32-bytes']) assert.ok(!bundle.includes(secret));
  const planned = await cli('data', 'plan', '--project', project);
  assert.equal(planned.plan.version, 1);
  assert.equal(planned.plan.alreadyApplied, false);
  assert.ok(planned.plan.operations.length > 0);
  const applied = await cli('data', 'apply', '--project', project);
  assert.equal(applied.verification.ready, true);
  assert.equal(applied.verification.version, 1);
  await ownerPage.goto(first.url + '/notes');
  await ownerPage.getByRole('heading', {name: 'Notes app'}).waitFor();
  await ownerPage.getByLabel('笔记内容').fill('browser-created');
  await ownerPage.getByRole('button', {name: '保存笔记'}).click();
  await ownerPage.getByText('browser-created').waitFor();
  ownerPage.once('dialog', dialog => dialog.accept('browser-updated'));
  await ownerPage.getByRole('button', {name: '编辑笔记 browser-created'}).click();
  await ownerPage.getByText('browser-updated').waitFor();
  await ownerPage.getByRole('button', {name: '删除笔记 browser-updated'}).click();
  await ownerPage.getByText('还没有笔记。').waitFor();
  await ownerPage.getByRole('button', {name: 'Run CRUD'}).click();
  await ownerPage.getByText('CRUD passed').waitFor();
  const ownerAppID = await ownerPage.locator('body').getAttribute('data-user');
  assert.ok(ownerAppID && /^[a-f0-9]{32}$/.test(ownerAppID));
  assert.ok((await ownerContext.cookies()).every(c => c.httpOnly && c.secure && !c.domain.startsWith('.')));
  const visitorContext = await browser.newContext({ignoreHTTPSErrors: false});
  const visitorPage = await visitorContext.newPage();
  await visitorPage.goto(origin + '/_test/visitor');
  await visitorPage.goto(first.url + '/notes');
  await visitorPage.getByRole('button', {name: '申请访问'}).click();
  await visitorPage.getByRole('heading', {name: '申请已提交'}).waitFor();
  await visitorPage.goto(first.url + '/notes');
  await visitorPage.getByRole('heading', {name: '申请审核中'}).waitFor();
  const pendingIdentity = await visitorContext.request.get(first.url + '/_cellapp/me');
  assert.equal(pendingIdentity.status(), 403);
  assert.equal((await pendingIdentity.json()).error, 'access_pending');
  await ownerPage.goto(origin + '/applications/' + metadata.appId);
  await ownerPage.getByText('Table version').waitFor();
  await ownerPage.getByRole('button', {name: 'Approve', exact: true}).click();
  await ownerPage.getByRole('button', {name: 'Confirm', exact: true}).click();
  await ownerPage.getByRole('status').filter({hasText: 'Access updated.'}).waitFor();
  await visitorPage.goto(first.url + '/notes');
  await visitorPage.getByRole('heading', {name: 'Notes app'}).waitFor();
  const visitorAppID = await visitorPage.locator('body').getAttribute('data-user');
  assert.ok(visitorAppID && visitorAppID !== ownerAppID);
  await visitorPage.getByRole('button', {name: 'Run CRUD'}).click();
  await visitorPage.getByText('CRUD passed').waitFor();
  const ownerCookie = (await ownerContext.cookies(first.url)).find(c => c.name === '__Host-cellapp')!;
  const visitorCookie = (await visitorContext.cookies(first.url)).find(c => c.name === '__Host-cellapp')!;
  assert.notEqual(ownerCookie.value, visitorCookie.value);
  const privateRow = crypto.randomUUID();
  assert.equal((await ownerContext.request.post(first.url + '/rest/v1/notes', {headers: {Origin: first.url}, data: {id: privateRow, owner_id: ownerAppID, body: 'private'}})).status(), 201);
  const invisible = await visitorContext.request.get(first.url + '/rest/v1/notes?select=id&id=eq.' + privateRow);
  assert.equal(invisible.status(), 200);
  assert.deepEqual(await invisible.json(), []);
  await ownerPage.getByRole('button', {name: 'Revoke', exact: true}).click();
  await ownerPage.getByRole('button', {name: 'Confirm', exact: true}).click();
  await ownerPage.getByText('No user grants.').waitFor();
  const deniedIdentity = await visitorContext.request.get(first.url + '/_cellapp/me');
  assert.equal(deniedIdentity.status(), 403);
  assert.equal((await deniedIdentity.json()).error, 'access_denied');
  await visitorPage.goto(first.url + '/notes');
  await visitorPage.getByRole('heading', {name: '申请未通过'}).waitFor();
  await visitorPage.getByLabel('访问密钥').fill(accessKey);
  await visitorPage.getByRole('button', {name: '授权访问'}).click();
  await visitorPage.getByText('访问已被所有者撤销').waitFor();
  const anotherContext = await browser.newContext({ignoreHTTPSErrors: false});
  const anotherPage = await anotherContext.newPage();
  await anotherPage.goto(origin + '/_test/visitor');
  await anotherPage.goto(first.url + '/notes');
  await anotherPage.getByLabel('访问密钥').fill(accessKey);
  await anotherPage.getByRole('button', {name: '授权访问'}).click();
  await anotherPage.getByRole('heading', {name: 'Notes app'}).waitFor();
  await ownerPage.getByRole('button', {name: 'Rotate access key'}).click();
  await ownerPage.getByRole('button', {name: 'Confirm', exact: true}).click();
  await ownerPage.getByRole('heading', {name: 'New access key'}).waitFor();
  await anotherPage.reload();
  await anotherPage.getByRole('heading', {name: 'Notes app'}).waitFor();
  await ownerPage.getByRole('button', {name: 'Make public'}).click();
  await ownerPage.getByRole('button', {name: 'Confirm', exact: true}).click();
  await ownerPage.getByText('Public to signed-in users').waitFor();
  await visitorPage.goto(first.url + '/notes');
  await visitorPage.getByRole('heading', {name: 'Notes app'}).waitFor();
  await ownerPage.getByRole('button', {name: 'Restrict access'}).click();
  await ownerPage.getByRole('button', {name: 'Confirm', exact: true}).click();
  await ownerPage.getByRole('button', {name: 'Make public'}).waitFor();
  assert.equal((await visitorContext.request.get(first.url + '/app.js')).status(), 403);
  assert.equal((await anotherContext.request.get(first.url + '/app.js')).status(), 200);
  const secondProject = join(root, 'second');
  await mkdir(join(secondProject, 'dist'), {recursive: true});
  await writeFile(join(secondProject, 'dist', 'index.html'), '<h1>Second app</h1>');
  const second = await deploy(client, secondProject, {output: 'dist'}, () => {});
  assert.equal((await anotherContext.request.get(second.url + '/rest/v1/notes?select=id')).status(), 401);
  await ownerPage.goto(second.url);
  await ownerPage.getByRole('heading', {name: 'Second app'}).waitFor();
  const secondCookie = (await ownerContext.cookies(second.url)).find(c => c.name === '__Host-cellapp')!;
  assert.notEqual(secondCookie.value, ownerCookie.value);
  for (const path of ['/auth/v1/user', '/storage/v1/object', '/functions/v1/test', '/realtime/v1', '/rest/v1/rpc/test']) {
    const unsupported: APIResponse = await anotherContext.request.get(first.url + path);
    assert.notEqual(unsupported.status(), 200);
    const errorBody: unknown = await unsupported.json();
    assert.ok(errorBody && typeof errorBody === 'object' && 'error' in errorBody && typeof errorBody.error === 'string');
  }
  await ownerPage.goto(origin + '/applications/' + metadata.appId);
  await ownerPage.getByRole('button', {name: 'Delete application'}).click();
  await ownerPage.getByRole('button', {name: 'Confirm', exact: true}).click();
  await ownerPage.getByRole('heading', {name: 'Applications', exact: true}).waitFor();
  assert.equal((await anotherContext.request.get(first.url)).status(), 404);
  console.log('HTTPS browser + real PostgreSQL/PostgREST/MinIO: login, grants, requests, key rotation, revocation, public access, CRUD, isolation and deletion passed.');
} finally {
  await browser.close(); await rm(root, {recursive: true, force: true});
}
